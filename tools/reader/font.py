def _parse():
    glyphs, lines = {}, [l for l in RAW.strip().split("\n")]
    i = 0
    while i < len(lines):
        name = lines[i]; i += 1
        rows = []
        while i < len(lines) and len(lines[i]) == 5 and set(lines[i]) <= set(".#"):
            rows.append(lines[i]); i += 1
        while len(rows) < 9: rows.append(".....")
        glyphs[name] = [[c == "#" for c in r] for r in rows]
    return glyphs


GLYPHS = _parse()
ARROWS = [k for k in GLYPHS if k.startswith(">")]
# characters the reader can output; index 0 is the CTC blank
CHARSET = "0123456789/.:-+*()>" + "ABCDEFGHIJKLMNOPQRSTUVWXYZ" + "abcdefghijklmnopqrstuvwxyz"


def glyph(ch, rng=None):
    """Glyph for a character of a label string; '>' picks one of the arrows."""
    if ch == ">":
        return GLYPHS[ARROWS[rng.integers(len(ARROWS))] if rng is not None else ARROWS[0]]
    return GLYPHS[ch]


if __name__ == "__main__":
    missing = [c for c in CHARSET if c != ">" and c not in GLYPHS]
    print(len(GLYPHS), "glyphs; missing:", missing)
